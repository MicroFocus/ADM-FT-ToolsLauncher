using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Numerics;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml;

namespace HpToolsLauncher.Common
{
    /// <summary>
    /// Converts an XML results file (generated by FTToolsLauncher) to the simplified JUnit report 
    /// <code>
    /// result
    ///   keepLongStdio, duration
    ///   suites/suite
    ///     file, name, duration
    ///     cases/case
    ///       duration, className, testName, skipped, skippedMessage, stdout, errorStackTrace, errorDetails
    /// </code>
    /// </summary>
    public class JUnitResultConverter
    {
        private const string TESTSUITES = "testsuites";
        private const string TESTSUITE = "testsuite";
        private const string TESTCASE = "testcase";
        private const string ERROR = "error";
        private const string FAILURE = "failure";
        private const string SKIPPED = "skipped";
        private const string SYSTEM_OUT = "system-out";
        private const string SYSTEM_ERR = "system-err";

        private static readonly Regex InvalidSuiteNameChars = new(@"[/\\:?#%<>]", RegexOptions.Compiled);
        // mimics the JavaScript parseFloat() accepted prefix
        private static readonly Regex JsFloatPrefix = new(@"^[+-]?(Infinity|([0-9]+\.?[0-9]*|\.[0-9]+)([eE][+-]?[0-9]+)?)", RegexOptions.Compiled);
        // JavaScript WhiteSpace + LineTerminator chars (used by String.prototype.trim() and parseFloat()), which differ from char.IsWhiteSpace()
        private static readonly char[] JsWhiteSpaceChars =
        [
            '\t', '\n', '\v', '\f', '\r', ' ', '\u00A0', '\u1680',
            '\u2000', '\u2001', '\u2002', '\u2003', '\u2004', '\u2005', '\u2006', '\u2007', '\u2008', '\u2009', '\u200A',
            '\u2028', '\u2029', '\u202F', '\u205F', '\u3000', '\uFEFF'
        ];
        private static readonly BigInteger TenPow5 = new(100000);

        public JUnitResultConverter(string inputFile, string outputFile, bool keepLongStdio = true)
        {
            InputFile = inputFile;
            OutputFile = outputFile;
            KeepLongStdio = keepLongStdio;
            Suites = [];
        }

        public string InputFile { get; private set; }

        public string OutputFile { get; private set; }

        public bool KeepLongStdio { get; private set; }

        public double Duration { get; private set; }

        public List<SuiteResult> Suites { get; private set; }

        /// <summary>
        /// Checks whether the specified file is a JUnit results XML file (root element is "testsuites" or "testsuite").
        /// An empty file is accepted too, since it is converted to an empty suite.
        /// </summary>
        public static bool IsJUnitResultsFile(string path)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(path) || !File.Exists(path))
                {
                    return false;
                }

                if (new FileInfo(path).Length == 0)
                {
                    return true;
                }

                using XmlReader reader = XmlReader.Create(path, new XmlReaderSettings { DtdProcessing = DtdProcessing.Ignore, XmlResolver = null });
                if (reader.MoveToContent() == XmlNodeType.Element)
                {
                    return reader.Name == TESTSUITES || reader.Name == TESTSUITE;
                }
            }
            catch
            {
            }

            return false;
        }

        /// <summary>
        /// Converts <paramref name="inputFile"/> and saves the simplified JUnit report to <paramref name="outputFile"/>.
        /// </summary>
        public static bool ConvertAndSave(string inputFile, string outputFile, bool keepLongStdio = true)
        {
            JUnitResultConverter converter = new(inputFile, outputFile, keepLongStdio);
            return converter.Convert() && converter.SaveFile();
        }

        public bool Convert()
        {
            Suites.Clear();
            Duration = 0;

            try
            {
                string fileName = Path.GetFileName(InputFile);
                if (new FileInfo(InputFile).Length == 0)
                {
                    Add(new SuiteResult(fileName));
                    return true;
                }

                List<SuiteResult> parsed;
                try
                {
                    parsed = ParseXml(InputFile, fileName, KeepLongStdio);
                }
                catch (Exception ex)
                {
                    // same as TypeScript: a parse failure is logged and results in no suites
                    ConsoleWriter.WriteErrLine(string.Format("Failed to parse [{0}]: {1}", InputFile, ex.Message));
                    return true;
                }

                foreach (SuiteResult sr in parsed)
                {
                    Add(sr);
                }

                return true;
            }
            catch (Exception ex)
            {
                ConsoleWriter.WriteErrLine(ex.Message);
                return false;
            }
        }

        public bool SaveFile()
        {
            try
            {
                if (File.Exists(OutputFile))
                {
                    File.Delete(OutputFile);
                }

                File.WriteAllText(OutputFile, ToXml(), new UTF8Encoding(false));
                return true;
            }
            catch (Exception ex)
            {
                ConsoleWriter.WriteErrLine(ex.Message);
                return false;
            }
        }

        public string ToXml()
        {
            StringBuilder xml = new();
            xml.Append("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"no\"?>\n");
            xml.Append("<result>\n");
            xml.Append("\t<keepLongStdio>").Append(ToJsBool(KeepLongStdio)).Append("</keepLongStdio>\n");
            xml.Append("\t<duration>").Append(ToFixed5(Duration)).Append("</duration>\n");
            xml.Append("\t<suites>\n");
            foreach (SuiteResult suite in Suites)
            {
                suite.AppendXml(xml, 2);
            }
            xml.Append("\t</suites>\n");
            xml.Append("</result>\n");
            return xml.ToString();
        }

        private void Add(SuiteResult sr)
        {
            foreach (SuiteResult s in Suites)
            {
                if (s.Name == sr.Name)
                {
                    // same suite name and timestamp: considered a duplicate and skipped
                    if (s.Timestamp == sr.Timestamp)
                    {
                        return;
                    }

                    Duration += sr.Duration;
                    s.Merge(sr);
                    return;
                }
            }

            Suites.Add(sr);
            Duration += sr.Duration;
        }

        private static List<SuiteResult> ParseXml(string path, string fileName, bool keepLongStdio)
        {
            List<SuiteResult> result = [];
            List<SuiteResult> suiteStack = [];
            SuiteResult testSuite = null;
            CaseResult testCase = null;
            StringBuilder currentText = new();
            Dictionary<string, string> attrs = null;
            string nodeName = string.Empty;

            void OnOpenTag()
            {
                if (nodeName == TESTSUITE)
                {
                    testSuite = new SuiteResult(fileName, attrs);
                    result.Add(testSuite);
                    suiteStack.Add(testSuite);
                }
                else if (nodeName == TESTCASE)
                {
                    if (testSuite == null)
                    {
                        ConsoleWriter.WriteLine("Testcase found outside of a testsuite, skipping.");
                        return;
                    }
                    testCase = new CaseResult(testSuite, attrs);
                }
                else if (nodeName == ERROR || nodeName == FAILURE)
                {
                    currentText.Clear();
                }
                else if (nodeName == SKIPPED)
                {
                    if (testCase != null)
                    {
                        testCase.Skipped = true;
                        testCase.SkippedMessage = GetAttr(attrs, "message") ?? string.Empty;
                    }
                }
            }

            void OnText(string text)
            {
                // the TypeScript sax parser runs with trim=true and does not emit empty text
                text = text.Trim(JsWhiteSpaceChars);
                if (text.Length == 0 || testCase == null)
                {
                    return;
                }

                if (nodeName == SYSTEM_OUT)
                {
                    testCase.Stdout = PossiblyTrimStdio(testCase, keepLongStdio, text);
                }
                else if (nodeName == SYSTEM_ERR)
                {
                    testCase.Stderr = PossiblyTrimStdio(testCase, keepLongStdio, text);
                }
                else if (nodeName == ERROR || nodeName == FAILURE)
                {
                    currentText.Append(text);
                }
            }

            void OnCloseTag(string tagName)
            {
                if (testSuite == null)
                {
                    return;
                }

                if (testCase != null)
                {
                    if (tagName == TESTCASE)
                    {
                        testSuite.AddCase(testCase);
                        testCase = null;
                    }
                    else if (tagName == ERROR || tagName == FAILURE)
                    {
                        testCase.ErrorStackTrace = currentText.ToString();
                        string message = GetAttr(attrs, "message");
                        if (!string.IsNullOrEmpty(message))
                        {
                            testCase.ErrorDetails = message;
                        }
                    }
                }
                else if (tagName == TESTSUITE)
                {
                    suiteStack.RemoveAt(suiteStack.Count - 1);
                    testSuite = suiteStack.Count > 0 ? suiteStack[suiteStack.Count - 1] : null;
                }
            }

            // Normalization=false keeps the original line endings (e.g. CRLF) in texts and attributes, as the TypeScript parser does
            using XmlTextReader reader = new(path)
            {
                Normalization = false,
                DtdProcessing = DtdProcessing.Ignore,
                XmlResolver = null,
                WhitespaceHandling = WhitespaceHandling.None
            };

            while (reader.Read())
            {
                switch (reader.NodeType)
                {
                    case XmlNodeType.Element:
                        bool isEmptyElement = reader.IsEmptyElement;
                        nodeName = reader.Name;
                        attrs = ReadAttributes(reader);
                        OnOpenTag();
                        if (isEmptyElement)
                        {
                            OnCloseTag(nodeName);
                        }
                        break;

                    // CDATA sections are intentionally ignored, as the TypeScript parser does
                    case XmlNodeType.Text:
                        OnText(reader.Value);
                        break;

                    case XmlNodeType.EndElement:
                        OnCloseTag(reader.Name);
                        break;
                }
            }

            return result;
        }

        private static Dictionary<string, string> ReadAttributes(XmlReader reader)
        {
            Dictionary<string, string> attrs = [];
            if (reader.MoveToFirstAttribute())
            {
                do
                {
                    attrs[reader.Name] = reader.Value;
                } while (reader.MoveToNextAttribute());
                reader.MoveToElement();
            }
            return attrs;
        }

        private static string GetAttr(Dictionary<string, string> attrs, string name)
        {
            return attrs != null && attrs.TryGetValue(name, out string value) ? value : null;
        }

        private static string PossiblyTrimStdio(CaseResult testCase, bool keepLongStdio, string stdio)
        {
            if (stdio == null || keepLongStdio)
            {
                return stdio;
            }

            int len = stdio.Length;
            int halfMaxSize = string.IsNullOrEmpty(testCase.ErrorStackTrace) ? 500 : 50000;
            int middle = len - halfMaxSize * 2;
            if (middle <= 0)
            {
                return stdio;
            }

            return stdio.Substring(0, halfMaxSize) + "\n...[truncated " + middle + " chars]...\n" + stdio.Substring(len - halfMaxSize, halfMaxSize);
        }

        private static double ParseTimeToFloat(string time)
        {
            if (string.IsNullOrEmpty(time))
            {
                return double.NaN;
            }

            // same as JavaScript: time.replace(",", "") replaces only the first occurrence
            int commaIndex = time.IndexOf(',');
            if (commaIndex >= 0)
            {
                time = time.Remove(commaIndex, 1);
            }

            Match m = JsFloatPrefix.Match(time.TrimStart(JsWhiteSpaceChars));
            if (!m.Success)
            {
                return double.NaN;
            }

            string value = m.Value;
            if (value.EndsWith("Infinity", StringComparison.Ordinal))
            {
                return value[0] == '-' ? double.NegativeInfinity : double.PositiveInfinity;
            }

            try
            {
                return double.Parse(value, NumberStyles.Float, CultureInfo.InvariantCulture);
            }
            catch (OverflowException)
            {
                return value[0] == '-' ? double.NegativeInfinity : double.PositiveInfinity;
            }
        }

        /// <summary>
        /// Same as JavaScript Number.prototype.toFixed(5): rounds the exact binary value half-up,
        /// whereas .NET Framework "F5" first rounds to 15 significant digits (e.g. 0.000035 gives "0.00003" in JS, but "0.00004" with "F5").
        /// </summary>
        private static string ToFixed5(double value)
        {
            if (double.IsNaN(value))
            {
                return "NaN";
            }
            if (double.IsInfinity(value))
            {
                return value > 0 ? "Infinity" : "-Infinity";
            }
            if (Math.Abs(value) >= 1e21)
            {
                // JS falls back to Number.prototype.toString() (exponential notation)
                return value.ToString("R", CultureInfo.InvariantCulture).Replace("E", "e");
            }

            string sign = value < 0 ? "-" : string.Empty;
            long bits = BitConverter.DoubleToInt64Bits(Math.Abs(value));
            int exp = (int)((bits >> 52) & 0x7FF);
            long mantissa = bits & 0xFFFFFFFFFFFFFL;
            if (exp == 0)
            {
                exp = 1; // subnormal
            }
            else
            {
                mantissa |= 1L << 52;
            }
            int exp2 = exp - 1075;

            BigInteger n;
            if (exp2 >= 0)
            {
                n = (new BigInteger(mantissa) << exp2) * TenPow5;
            }
            else
            {
                BigInteger den = BigInteger.One << -exp2;
                n = BigInteger.DivRem(new BigInteger(mantissa) * TenPow5, den, out BigInteger rem);
                if (rem * 2 >= den)
                {
                    n += 1;
                }
            }

            string digits = n.ToString(CultureInfo.InvariantCulture).PadLeft(6, '0');
            return sign + digits.Substring(0, digits.Length - 5) + "." + digits.Substring(digits.Length - 5);
        }

        private static string ToJsBool(bool value)
        {
            return value ? "true" : "false";
        }

        private static string EscapeXml(string str)
        {
            if (string.IsNullOrEmpty(str))
            {
                return string.Empty;
            }

            return str
                .Replace("&", "&amp;")
                .Replace("<", "&lt;")
                .Replace(">", "&gt;")
                .Replace("\"", "&quot;")
                .Replace("'", "&apos;");
        }

        public class SuiteResult
        {
            public SuiteResult(string xmlResFileName, Dictionary<string, string> attrs = null)
            {
                Cases = [];
                if (attrs != null)
                {
                    string name = GetAttr(attrs, "name");
                    if (name == null)
                    {
                        name = string.Format("({0})", xmlResFileName);
                    }
                    else
                    {
                        string pkg = GetAttr(attrs, "package");
                        if (!string.IsNullOrEmpty(pkg))
                        {
                            name = string.Format("{0}.{1}", pkg, name);
                        }
                    }

                    Name = InvalidSuiteNameChars.Replace(name, "_");
                    File = xmlResFileName;
                    Timestamp = GetAttr(attrs, "timestamp") ?? string.Empty;
                    string time = GetAttr(attrs, "time");
                    if (!string.IsNullOrEmpty(time))
                    {
                        Duration = ParseTimeToFloat(time);
                    }
                }
                else
                {
                    Name = InvalidSuiteNameChars.Replace(string.Format("({0})", xmlResFileName), "_");
                    Timestamp = string.Empty;
                }
            }

            public string File { get; private set; }
            public string Name { get; private set; }
            public string Timestamp { get; private set; }
            public double Duration { get; private set; }
            public List<CaseResult> Cases { get; private set; }

            // Like the TypeScript implementation, the case durations are always added to the suite duration.
            public void AddCase(CaseResult cr)
            {
                Cases.Add(cr);
                Duration += cr.Duration;
            }

            public void Merge(SuiteResult sr)
            {
                foreach (CaseResult cr in sr.Cases)
                {
                    cr.Parent = this;
                    AddCase(cr);
                }
            }

            public void AppendXml(StringBuilder xml, int indent)
            {
                string tabs = new('\t', indent);
                xml.Append(tabs).Append("<suite>\n");
                xml.Append(tabs).Append("\t<file>").Append(EscapeXml(File)).Append("</file>\n");
                xml.Append(tabs).Append("\t<name>").Append(EscapeXml(Name)).Append("</name>\n");
                xml.Append(tabs).Append("\t<duration>").Append(ToFixed5(Duration)).Append("</duration>\n");
                xml.Append(tabs).Append("\t<cases>\n");
                foreach (CaseResult testCase in Cases)
                {
                    testCase.AppendXml(xml, indent + 2);
                }
                xml.Append(tabs).Append("\t</cases>\n");
                xml.Append(tabs).Append("</suite>\n");
            }
        }

        public class CaseResult
        {
            public CaseResult(SuiteResult parent, Dictionary<string, string> attrs)
            {
                string classname = GetAttr(attrs, "classname") ?? parent.Name;
                string name = GetAttr(attrs, "name");
                if (string.IsNullOrEmpty(classname) && name != null && name.Contains("."))
                {
                    classname = name.Substring(0, name.LastIndexOf('.'));
                    name = name.Substring(name.LastIndexOf('.') + 1);
                }

                ClassName = classname ?? "unnamed";
                TestName = name;
                Parent = parent;
                Duration = ParseTimeToFloat(GetAttr(attrs, "time"));
                ReportPath = GetAttr(attrs, "report");
                ErrorStackTrace = string.Empty;
                ErrorDetails = string.Empty;
            }

            public double Duration { get; private set; }
            public string ClassName { get; private set; }
            public string TestName { get; private set; }
            public bool Skipped { get; set; }
            public string SkippedMessage { get; set; }
            public string Stdout { get; set; }
            public string Stderr { get; set; }
            public string ErrorStackTrace { get; set; }
            public string ErrorDetails { get; set; }
            public string ReportPath { get; private set; }
            public SuiteResult Parent { get; set; }

            public void AppendXml(StringBuilder xml, int indent)
            {
                string tabs = new('\t', indent);
                xml.Append(tabs).Append("<case>\n");
                xml.Append(tabs).Append("\t<duration>").Append(ToFixed5(Duration)).Append("</duration>\n");
                xml.Append(tabs).Append("\t<className>").Append(EscapeXml(ClassName)).Append("</className>\n");
                xml.Append(tabs).Append("\t<testName>").Append(EscapeXml(TestName)).Append("</testName>\n");
                xml.Append(tabs).Append("\t<skipped>").Append(ToJsBool(Skipped)).Append("</skipped>\n");
                xml.Append(tabs).Append("\t<skippedMessage>").Append(EscapeXml(SkippedMessage)).Append("</skippedMessage>\n");
                xml.Append(tabs).Append("\t<stdout>").Append(EscapeXml(Stdout)).Append("</stdout>\n");
                xml.Append(tabs).Append("\t<errorStackTrace>").Append(EscapeXml(ErrorStackTrace)).Append("</errorStackTrace>\n");
                xml.Append(tabs).Append("\t<errorDetails>").Append(EscapeXml(ErrorDetails)).Append("</errorDetails>\n");
                xml.Append(tabs).Append("</case>\n");
            }
        }
    }
